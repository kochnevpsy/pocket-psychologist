// Функция определения реакции Сонди
function evaluateSzondiReaction(plusCount, minusCount) {
  if (plusCount >= 2 && minusCount >= 2) {
    return { type: "+-", symbol: "±", label: "Амбивалентная реакция (внутренний конфликт влечения)" };
  }
  if (plusCount >= 2 && minusCount <= 1) {
    const isCharged = plusCount >= 4;
    return { 
      type: "+", 
      symbol: isCharged ? "+!" : "+", 
      label: isCharged ? "Гипервыраженная положительная реакция" : "Положительная реакция (удовлетворение / принятие)" 
    };
  }
  if (minusCount >= 2 && plusCount <= 1) {
    const isCharged = minusCount >= 4;
    return { 
      type: "-", 
      symbol: isCharged ? "-!" : "-", 
      label: isCharged ? "Гипервыраженная отрицательная реакция" : "Отрицательная реакция (вытеснение / защита)" 
    };
  }
  return { type: "0", symbol: "0", label: "Нулевая реакция (покой / сублимация влечения)" };
}

